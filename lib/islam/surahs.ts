/** Intervalles de révision (jours) pour les sourates mémorisées. */
export const REVIEW_STEPS = [1, 3, 7, 14, 30, 60, 120] as const;

export function nextInterval(current: number, quality: "good" | "hard"): number {
  const idx = REVIEW_STEPS.findIndex((s) => s >= current);
  const i = idx === -1 ? REVIEW_STEPS.length - 1 : idx;
  if (quality === "hard") return REVIEW_STEPS[Math.max(0, i - 1)];
  return REVIEW_STEPS[Math.min(REVIEW_STEPS.length - 1, i + 1)];
}
